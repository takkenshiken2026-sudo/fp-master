def explanation_correct_from_past(explanation: str, correct: int) -> str:
    exp = (explanation or "").strip()
    if not exp:
        return f"正解は{correct}です。"
    # 「正解はNです。」以降を要点として使用
    m = re.match(rf"正解は{correct}[です。．]*\s*", exp)
    body = exp[m.end() :] if m else exp
    body = body.strip()
    if len(body) > 220:
        body = body[:220].rstrip("。") + "。"
    return body or f"正解は{correct}の選択肢が、資料および制度の定めと一致します。"


def build_row(question_no: int, source_ref: str, past: dict) -> dict:
    year, _, qpart = source_ref.partition("-jitsugi-")
    qn = int(qpart)
    diagram_id = norm(past.get("diagram_id"))
    if diagram_id and not diagram_has_content(diagram_id):
        diagram_id = ""

    stem = STEM_TWEAKS.get(source_ref) or collapse_stem(past.get("stem") or "")
    correct = str(past.get("correct") or "").strip()
    cor_int = int(correct)
    explanation = (past.get("explanation") or "").strip()
    if f"正解は{cor_int}" not in norm(explanation):
        explanation = f"正解は{cor_int}です。{explanation}"

    choice_notes = CHOICE_NOTES.get(source_ref)
    if not choice_notes:
        raise ValueError(f"CHOICE_NOTES missing for {source_ref}")

    from tools.seed_practice_batch1 import row

    kwargs: dict = dict(
        question_no=question_no,
        category=(past.get("category") or "").strip(),
        tags=f"{T};source:{source_ref}-v1",
        source_ref=source_ref,
        stem=stem,
        choice_1=(past.get("choice_1") or "").strip(),
        choice_2=(past.get("choice_2") or "").strip(),
        choice_3=(past.get("choice_3") or "").strip(),
        correct=correct,
        explanation=explanation,
        explanation_summary=f"{year}年実技第{qn}問の演習問題です。",
        explanation_correct=explanation_correct_from_past(explanation, cor_int),
        explanation_choices=choice_notes,
        explanation_point=POINTS.get(source_ref, ""),
    )
    if diagram_id:
        kwargs["diagram_id"] = diagram_id
    return row(**kwargs)


