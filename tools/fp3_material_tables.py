def _t(
    title: str,
    rows: list[list[Any]],
    *,
    headers: list[str] | None = None,
    unit: str = "",
    dense: bool = True,
) -> dict[str, Any]:
    d: dict[str, Any] = {
        "type": "fp_table",
        "title": title,
        "rows": rows,
        "dense": dense,
    }
    if headers:
        d["headers"] = headers
    if unit:
        d["unit"] = unit
    return d


def _note(text: str) -> list[dict[str, Any]]:
    return [{"text": text, "note": True}]


def _txt(title: str, body: str) -> dict[str, Any]:
    return {"type": "fp_text_block", "title": title, "body": body}


